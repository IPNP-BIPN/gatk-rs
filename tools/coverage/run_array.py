#!/usr/bin/env python3
"""Run a covering array against the oracle, and optionally against the port binary.

The arrays under `tools/coverage/arrays/` are generated by `covering.py` from the pinned
inventory; they are rows of argument assignments and nothing more. This turns each row into a
command line, runs it, and records what came back.

Two modes, and the difference is the whole point of Milestone C:

* **oracle only** (the default) produces a corpus: one row per array row, in the dump format every
  conformance suite uses, so the result can be committed and compared like any other golden. It
  also answers a question nothing else does, which is how many DISTINCT outputs the argument
  surface actually produces. An argument that changes nothing on this corpus is an argument the
  corpus cannot test, and that is worth knowing before a port is measured against it.
* **with `--port`**, each row also runs `gatk-rs` and the two answers are compared. That number is
  the fraction of the argument surface the port reproduces, which is the figure the dashboard's
  argument-coverage column has said `not measured` for since the arrays were generated.

    python3 tools/coverage/run_array.py --tool IndexFeatureFile
    python3 tools/coverage/run_array.py --tool IndexFeatureFile --port target/release/gatk-rs
"""

import argparse
import hashlib
import re
import json
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ARRAYS = REPO / "tools" / "coverage" / "arrays"
IMAGE = "gatk-rs-oracle:4.6.2.0"
PLATFORM = "linux/amd64"

# Values that mean "the argument is absent", so a held-at value carrying one must not be passed.
ABSENT = {"None", "null", "[]", ""}


# A corpus built once and handed to every row, by `measure.py` when it runs many tools. The files are
# mounted READ-ONLY into every container, so one copy serves any number of runs, concurrent ones
# included; `None` builds a corpus of this run's own.
FIXTURES_DIR = None


def fixtures_of(workdir):
    """Where this run's corpus is: the shared one when there is one, else its own."""
    return Path(FIXTURES_DIR) if FIXTURES_DIR else workdir / "fixtures"


def build_fixtures(workdir):
    """Materialize the corpus with MakeFixtures.java, inside the pinned container."""
    fixtures = workdir / "fixtures"
    fixtures.mkdir(parents=True, exist_ok=True)
    command = (
        'cp /harness/MakeFixtures.java . && javac -cp "$ORACLE_CP" -d . MakeFixtures.java '
        '&& java -Dsamjdk.try_use_intel_deflater=false -cp ".:$ORACLE_CP" MakeFixtures /out'
    )
    result = subprocess.run(
        [
            "docker", "run", "--rm", "--platform", PLATFORM,
            "-v", f"{REPO}/tools/coverage:/harness:ro",
            "-v", f"{fixtures}:/out",
            "-w", "/work", IMAGE, command,
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(result.stdout[-2000:])
        print(result.stderr[-2000:])
        raise SystemExit("could not build the fixtures")
    return fixtures


def row_arguments(row, held):
    """The row's own assignments, plus the fixture values it cannot run without.

    An argument excluded with `source: "fixture"` has no default, so the row must carry it. One
    excluded with `source: "default"` is omitted: re-serializing a default is at best redundant,
    and for a collection it is wrong, the default coming back as one token with its brackets.
    """
    args = list(row["arguments"])
    covered = {a.split("=", 1)[0] for a in args}
    for entry in held:
        name, value = entry["argument"], entry.get("held_at")
        if entry.get("source") != "fixture" or name in covered:
            continue
        if value is None or str(value) in ABSENT:
            continue
        args.append(f"{name}={value}")
    return args


def as_cli(args, positional=(), tagged=(), lists=()):
    """Barclay long form: `--name value`, which is the syntax the claim is defined against.

    A POSITIONAL argument has no name to write, so it cannot come out of the array at all: every
    assignment there is `--name=value`. The values are a per-tool fixture instead, under
    `$positional`, and they go LAST, which is where a command line puts them and what the parser's
    own tokenizer expects. `CompareBaseQualities` is the tool that has them: its two SAM files are
    `@PositionalArguments(minElements = 2, maxElements = 2)`.
    """
    out = []
    for pair in args:
        name, _, value = pair.partition("=")
        if name in tagged:
            # One value naming several tagged inputs: `tag:path` words, each written as
            # `--name:tag path`. `VCFComparator` tells its two `--variant`s apart by tag alone, so
            # a value of this argument is the whole tagged pair rather than one file.
            for word in value.split():
                tag, _, path = word.partition(":")
                out += [f"{name}:{tag}", path]
            continue
        if name in lists:
            # One value naming a whole list, each word its own `--name word`: `VariantRecalibrator`
            # models every `--use-annotation` it is given together, so a list of one is a
            # different model and not a smaller sample of the same one.
            for word in value.split():
                out += [name, word]
            continue
        out += [name, value]
    out += list(positional)
    # Both sides are run through a shell inside the container, so a value carrying a shell
    # metacharacter has to survive it. `--select QUAL>50.0` was read as `--select QUAL` with the
    # rest taken as a redirect, on the reference and on the port alike: seven rows of
    # `SelectVariants`' array measured a ClassCastException over a bare `QUAL` instead of the
    # comparison the fixture wrote. Quoting is what a value with a space needs too.
    return [shlex.quote(token) for token in out]


def output_path(row_args):
    """Where this row asked its output to go, which is what the comparison reads back."""
    for pair in row_args:
        name, _, value = pair.partition("=")
        if name == "--output":
            return value
    return None


def clear(out_dir):
    """Empty an output directory between rows, whoever owns what is in it.

    A tool whose `--output` is a DIRECTORY leaves one here -- `SplitIntervals` writes a shard per
    file into one it creates itself -- and a directory the CONTAINER created belongs to root, so
    the host cannot remove it at all. Each run therefore opens with `rm -rf /work/out/*` INSIDE the
    container, and this is the best-effort half that keeps a host-owned leftover from accumulating.
    """
    for stale in out_dir.iterdir():
        try:
            if stale.is_dir():
                shutil.rmtree(stale)
            else:
                stale.unlink()
        except OSError:
            pass


def run_oracle(tool, row_args, workdir, positional=(), tagged=(), lists=()):
    """Run one row in the container. Returns (exit code, output as text or digest, error line)."""
    out_dir = workdir / "out"
    out_dir.mkdir(exist_ok=True)
    clear(out_dir)

    cli = " ".join(as_cli(row_args, positional, tagged, lists))
    # `gatk <Tool> <args>`: the tool name is the first token, which is the shape the bit-identity
    # claim is defined against, and the wrapper is what fixes the parser to Barclay.
    command = f'rm -rf /work/out/* && mkdir -p /work/tmp /work/tmp2 /work/out && java -cp "$ORACLE_CP" org.broadinstitute.hellbender.Main {tool} {cli}'
    result = subprocess.run(
        [
            "docker", "run", "--rm", "--platform", PLATFORM,
            "-v", f"{fixtures_of(workdir)}:/work/fixtures:ro",
            "-v", f"{out_dir}:/work/out",
            "-w", "/work", IMAGE, command,
        ],
        capture_output=True,
        text=True,
    )
    return (
        result.returncode,
        with_stdout(read_output(out_dir, row_args), result.stdout),
        first_error(result.stderr or result.stdout),
    )


def read_output(out_dir, row_args=()):
    """The row's output, as text where it is text and as a digest where it is not.

    An index is binary, so hashing it is what keeps the row measurable: the comparison needs to
    know whether the two sides produced the same bytes, and a digest answers that exactly.
    """
    # Recursive, because a directory output's files are the row's answer; their names are relative
    # to the output directory so two runs of one tool stay comparable.
    produced = sorted(p for p in out_dir.rglob("*") if p.is_file())
    if not produced:
        return ""
    parts = []
    for path in produced:
        raw = path.read_bytes()
        name = path.relative_to(out_dir).as_posix()
        if name.endswith(".tar.gz"):
            parts.append(f"{name}: {tar_gz_members(raw)}")
            continue
        if name.endswith(".zip"):
            parts.append(f"{name}: {zip_members(raw)}")
            continue
        if unordered_traversals(name, row_args):
            parts.append(f"{name}: {traversals_unordered(raw)}")
            continue
        if name.endswith(".img"):
            masked = bwa_image_masked(raw)
            if masked is not None:
                digest = hashlib.sha256(masked).hexdigest()
                parts.append(f"{name}: BWA IMAGE sha256={digest} bytes={len(raw)} (addresses masked)")
                continue
        try:
            parts.append(f"{name}: {without_start_time(raw.decode('utf-8'))}")
        except UnicodeDecodeError:
            digest = hashlib.sha256(raw).hexdigest()
            parts.append(f"{name}: BINARY sha256={digest} bytes={len(raw)}")
    return "\n".join(parts)


def unordered_traversals(name, row_args):
    """Whether this file is `LocalAssembler` output whose record order is the JVM's.

    The tool keeps its traversals in a `HashSet<Traversal>` whose hash is the list hash of the
    contigs', and a contig has no `hashCode` of its own: it is an identity hash. So the GFA's `O`
    lines, and under `--no-scaffolding` the FASTA's records, come out in an order (and a traversal
    found from both of its ends in an orientation) that changes from one JVM to the next. The
    scaffolds of the default FASTA are sorted by contig id before they are written, so that file
    is compared byte for byte, gzipped or not.
    """
    if name.endswith(".gfa"):
        return True
    no_scaffolding = any(arg == "--no-scaffolding=true" for arg in row_args)
    return no_scaffolding and (name.endswith(".fa") or name.endswith(".fa.gz"))


def traversals_unordered(raw):
    """A GFA's `O` lines, or a traversal FASTA's records, each in one orientation and sorted.

    A traversal read backwards is the same traversal: its contigs reversed, each in the other
    orientation, and its sequence reverse-complemented. The lesser of the two spellings stands for
    both. A FASTA record's `_t<n>` counter follows the order, so it is replaced by `_t*`.
    """
    import gzip

    data = gzip.decompress(raw) if raw[:2] == b"\x1f\x8b" else raw
    text = data.decode("utf-8")
    lines = text.split("\n")
    if lines and lines[0].startswith("H\t"):
        paths = [line for line in lines if line.startswith("O\t")]
        others = [line for line in lines if not line.startswith("O\t")]
        flip = {"+": "-", "-": "+"}

        def canonical(line):
            steps = line[len("O\t*\t"):].split(" ")
            reverse = [step[:-1] + flip[step[-1]] for step in reversed(steps)]
            return "O\t*\t" + min(" ".join(steps), " ".join(reverse))

        body = [line for line in others if line != ""]
        return "UNORDERED " + "\n".join(body + sorted(canonical(line) for line in paths))
    complement = str.maketrans("ACGTN", "TGCAN")
    records = []
    for header, sequence in zip(lines[0::2], lines[1::2]):
        name, _, path = header.partition(" ")
        prefix = re.sub(r"_t\d+$", "_t*", name)
        steps = path.split("+")
        reverse = "+".join(
            step[:-2] if step.endswith("RC") else step + "RC" for step in reversed(steps)
        )
        forward = (path, sequence)
        backward = (reverse, sequence.translate(complement)[::-1])
        chosen = min(forward, backward)
        records.append(f"{prefix} {chosen[0]}\n{chosen[1]}")
    return "UNORDERED " + "\n".join(sorted(records))


STARTED_ON = re.compile(r"^# Started on: .*$", re.MULTILINE)
# `MafOutputRenderer.writeHeader` stamps the header with `new Date()` through the pattern
# `yyyymmdd'T'hhmmss`, which is the wall clock again (the `mm` is minutes, not the month).
MAF_DATE = re.compile(r"^(##  Funcotator \S+ \| Date )\d{8}T\d{6}( \| )", re.MULTILINE)


def tar_gz_members(raw):
    """A tar.gz output as its members, sorted by name, each as text where it is text.

    `IOUtils.writeTarGz` stamps every entry with the time it was written and adds the files in the
    order `File.listFiles()` returns them, which is the file system's: two runs of the reference
    already differ in the archive's bytes. What the tool decides is which members there are and
    what each holds, so that is what is compared.
    """
    import gzip
    import io
    import tarfile

    try:
        archive = tarfile.open(fileobj=io.BytesIO(gzip.decompress(raw)), mode="r:")
    except (OSError, tarfile.TarError) as error:
        digest = hashlib.sha256(raw).hexdigest()
        return f"BINARY sha256={digest} bytes={len(raw)} (not a tar.gz: {error})"
    rendered = []
    for member in sorted(archive.getmembers(), key=lambda m: m.name):
        if not member.isfile():
            rendered.append(f"[{member.name}: {member.type!r}]")
            continue
        content = archive.extractfile(member).read()
        try:
            text = without_start_time(content.decode("utf-8"))
        except UnicodeDecodeError:
            text = f"BINARY sha256={hashlib.sha256(content).hexdigest()} bytes={len(content)}"
        if member.name.endswith(".alt_histogram"):
            text = histogram_columns_sorted(text)
        rendered.append(f"[{member.name}: {text}]")
    return "TAR.GZ " + " ".join(rendered)


def zip_members(raw):
    """A zip output as its members, sorted by name, each as text where it is text.

    `ZipUtils.zip` adds the files in `File.listFiles()` order and stamps each entry with the time
    it was written, and `ZipOutputStream` deflates at a level no argument reaches: what the tool
    decides is which members there are and what each holds, so that is what is compared.
    """
    import io
    import zipfile

    try:
        archive = zipfile.ZipFile(io.BytesIO(raw))
    except zipfile.BadZipFile as error:
        digest = hashlib.sha256(raw).hexdigest()
        return f"BINARY sha256={digest} bytes={len(raw)} (not a zip: {error})"
    rendered = []
    for name in sorted(archive.namelist()):
        content = archive.read(name)
        try:
            text = without_start_time(content.decode("utf-8"))
        except UnicodeDecodeError:
            text = f"BINARY sha256={hashlib.sha256(content).hexdigest()} bytes={len(content)}"
        rendered.append(f"[{name}: {text}]")
    return "ZIP " + " ".join(rendered)


def bwa_image_masked(raw):
    """A BWA-MEM index image with its addresses and padding zeroed, or None if it is not one.

    `BwaMemIndexImageCreator` writes the block `bwa_idx2mem` lays out, which copies BWA's C
    structures as they stand: the `sa` pointer of `bwt_t`, the `anns`, `ambs` and `fp_pac` pointers
    of `bntseq_t` and the `name` and `anno` pointers of every `bntann1_t` are addresses of the
    process that wrote them, and two runs of the reference already differ there
    (docs/pointers-that-reach-the-output.md). Which bytes they are is known from the layout, so
    they are masked here, with the structures' padding, and every other byte -- the transform, the
    occurrence counts, the sampled suffix array, the contigs, the holes and the packed bases -- is
    compared.
    """
    import struct

    try:
        bwt_size = struct.unpack_from("<Q", raw, 56)[0]
        n_sa = struct.unpack_from("<Q", raw, 1104)[0]
        bns = 1120 + bwt_size * 4 + n_sa * 8
        n_seqs = struct.unpack_from("<i", raw, bns + 8)[0]
        n_holes = struct.unpack_from("<i", raw, bns + 24)[0]
    except struct.error:
        return None
    if n_seqs < 0 or n_holes < 0:
        return None
    # bwt_t: the `bwt` pointer, the padding after `sa_intv`, the `sa` pointer. bntseq_t: `anns`,
    # then the padding after `n_holes`, `ambs` and `fp_pac`.
    fields = [(64, 72), (1100, 1104), (1112, 1120), (bns + 16, bns + 24), (bns + 28, bns + 48)]
    holes = bns + 48
    # bntamb1_t: the three bytes of padding after `amb`.
    fields += [(holes + 16 * h + 13, holes + 16 * h + 16) for h in range(n_holes)]
    anns = holes + 16 * n_holes
    # bntann1_t: `name` and `anno`.
    fields += [(anns + 40 * a + 24, anns + 40 * a + 40) for a in range(n_seqs)]
    if any(end > len(raw) for _, end in fields):
        return None
    masked = bytearray(raw)
    for start, end in fields:
        masked[start:end] = bytes(end - start)
    return bytes(masked)


def histogram_columns_sorted(text):
    """A metrics file whose histogram columns are put in label order, the bin column first.

    `CollectF1R2Counts`' depth-one histograms come out of a map keyed by a pair holding an enum,
    whose hash is an identity hash, so the reference writes the same columns in a different order
    from one JVM to the next. The columns are what the tool decides; their order is not.
    """
    lines = text.split("\n")
    for index, line in enumerate(lines):
        if not line.startswith("## HISTOGRAM"):
            continue
        body = index + 1
        end = body
        while end < len(lines) and lines[end] != "":
            end += 1
        rows = [row.split("\t") for row in lines[body:end]]
        if not rows:
            break
        order = [0] + sorted(range(1, len(rows[0])), key=lambda column: rows[0][column])
        lines[body:end] = ["\t".join(row[column] for column in order) for row in rows]
        break
    return "\n".join(lines)


def without_start_time(text):
    """A metrics file with the one line that is the wall clock taken out, and a MAF's too.

    `CommandLineProgram.getMetricsFile` heads every metrics file with the command line and then
    `# Started on: <now>`, so two runs of the reference already differ there. The line is kept and
    its value replaced, which still measures that both sides write it, where, and that everything
    around it is the same; only the time of day is not compared.
    """
    text = STARTED_ON.sub("# Started on: <start time>", text)
    return MAF_DATE.sub(r"\g<1><date>\g<2>", text)


def first_error(text):
    """The refusal's own line.

    A rejected row is not a failed run: the reference refuses a block-compressed input whose
    output is not a `.tbi`, and that refusal is behaviour the port has to reproduce, message
    included, so it is recorded as the row's answer rather than thrown away as noise.
    """
    for line in text.split("\n"):
        if "Exception" in line or line.startswith("ERROR") or "A USER ERROR" in line:
            return line.strip()
    return text.strip().split("\n")[-1][:200] if text.strip() else ""


def run_port(binary, tool, row_args, workdir, positional=(), tagged=(), lists=()):
    """Run the port binary on the same row, IN THE CONTAINER, at the same paths.

    Not on the host, and the reason is the output itself: a Tribble index records the file it was
    built from, by path and by last-modified time. Run the port on the host and its index carries
    `/tmp/xxx/fixtures/reads.vcf` where the reference's carries `/work/fixtures/reads.vcf`, so the
    two differ by the length of a path and the comparison measures the mount point instead of the
    port. Running both sides at the same paths, over the same mounted files, is what makes the
    digests comparable at all.

    The binary therefore has to be a linux/amd64 one, which is what CI builds. A laptop that
    cannot produce one runs this without `--port` and gets the corpus, which is the half that does
    not need a port.
    """
    out_dir = workdir / "port"
    out_dir.mkdir(exist_ok=True)
    clear(out_dir)

    binary = Path(binary).resolve()
    cli = " ".join(as_cli(row_args, positional, tagged, lists))
    command = f"rm -rf /work/out/* && mkdir -p /work/tmp /work/tmp2 /work/out && /work/port-binary/{binary.name} {tool} {cli}"
    result = subprocess.run(
        [
            "docker", "run", "--rm", "--platform", PLATFORM,
            "-v", f"{fixtures_of(workdir)}:/work/fixtures:ro",
            "-v", f"{out_dir}:/work/out",
            "-v", f"{binary.parent}:/work/port-binary:ro",
            "-w", "/work", IMAGE, command,
        ],
        capture_output=True,
        text=True,
    )
    return (
        result.returncode,
        with_stdout(read_output(out_dir, row_args), result.stdout),
        first_error(result.stderr or result.stdout),
    )


def with_stdout(text, stdout):
    """The row's files, then what the tool printed.

    A tool whose answer is printed rather than written -- `CountReads`'s count, `FlagStat`'s
    table, the features `ExampleMultiFeatureWalker` prints as it walks -- left NOTHING here before,
    so every accepted row agreed with every other and the array measured its refusals alone. The
    log goes to stderr and is not compared; stdout is the tool's.
    """
    if not stdout:
        return text
    printed = f"stdout: {stdout}"
    return f"{text}\n{printed}" if text else printed


def outcome(code, text, error, keep_output=False):
    """One row's result, as the thing that will be compared: an output, or a refusal.

    A refusal is its exit status and its line, and for most tools that is all a failed run leaves
    worth comparing. A tool under `$output_on_failure` fails AFTER writing its answer, so the files
    it left are compared with the refusal rather than thrown away with it.
    """
    if code != 0:
        if keep_output and text:
            return f"EXIT={code} {error}\n{text}"
        return f"EXIT={code} {error}"
    return text


def escape(text):
    return text.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tool", required=True)
    parser.add_argument("--t", type=int, default=2)
    parser.add_argument("--port", help="the port binary to compare against")
    parser.add_argument("--corpus", help="where to write the corpus")
    parser.add_argument(
        "--fixtures-dir",
        help="a corpus MakeFixtures.java already built, to run against instead of building one",
    )
    options = parser.parse_args(argv)
    global FIXTURES_DIR
    FIXTURES_DIR = options.fixtures_dir

    array_path = ARRAYS / f"{options.tool}.t{options.t}.json"
    if not array_path.exists():
        raise SystemExit(f"no array at {array_path}; generate it with covering.py")
    array = json.loads(array_path.read_text())
    held = array.get("excluded", [])

    # `ignore_cleanup_errors` is not enough on its own and is kept for the rest: what a tool whose
    # `--output` is a DIRECTORY leaves behind belongs to ROOT, because the container created it,
    # and `shutil.rmtree` cannot remove it however the errors are handled. The container is what
    # takes it away again, in the `finally` below.
    with tempfile.TemporaryDirectory(
        prefix="gatk-coverage-", ignore_cleanup_errors=True
    ) as tmp:
        workdir = Path(tmp)
        try:
            return run_rows(options, array, held, workdir)
        finally:
            empty_output_in_container(workdir)


def empty_output_in_container(workdir):
    """`rm -rf` the output directory's contents as ROOT, which is who owns them.

    A tool that writes a DIRECTORY leaves one the host cannot remove at all, so the temporary
    directory's own teardown fails and a run that measured everything correctly exits non-zero.
    """
    for name in ("out", "port"):
        directory = workdir / name
        if not directory.is_dir():
            continue
        subprocess.run(
            [
                "docker", "run", "--rm", "--platform", PLATFORM,
                "-v", f"{directory}:/work/out",
                "-w", "/work", IMAGE, "rm -rf /work/out/*",
            ],
            capture_output=True,
            text=True,
        )


def positional_values(tool):
    """The `$positional` fixture values for a tool, which every row carries unchanged.

    They are not part of the array: an assignment there is `--name=value`, and a positional argument
    has no name. Holding them per tool is the same bargain a held-at fixture makes -- the values are
    present on every row rather than covered against each other -- and it is the only way a tool
    whose inputs are positional can be run at all.
    """
    path = REPO / "tools" / "coverage" / "fixtures.json"
    if not path.exists():
        return []
    fixtures = json.loads(path.read_text())
    return list(fixtures.get("per_tool", {}).get(tool, {}).get("$positional", []))


def output_on_failure(tool):
    """Whether a failed row's output files are part of its answer, per tool under
    `$output_on_failure`.

    `AlleleFrequencyQC` writes its metrics and only then runs an R script, which the image cannot,
    so EVERY row it accepts ends on a user error. Comparing the error alone would count twenty rows
    matched without reading the statistic once.
    """
    path = REPO / "tools" / "coverage" / "fixtures.json"
    if not path.exists():
        return False
    fixtures = json.loads(path.read_text())
    return bool(fixtures.get("per_tool", {}).get(tool, {}).get("$output_on_failure", False))


def tagged_arguments(tool):
    """The arguments whose fixture values are `tag:path` words, per tool under `$tagged`.

    A tagged input's tag is part of the command line and not of the value, so the array, which
    assigns values, cannot carry it. Declaring the argument tagged lets one value stand for a whole
    set of tagged inputs, which is the only way a tool that reads its inputs BY TAG can be run.
    """
    path = REPO / "tools" / "coverage" / "fixtures.json"
    if not path.exists():
        return ()
    fixtures = json.loads(path.read_text())
    return tuple(fixtures.get("per_tool", {}).get(tool, {}).get("$tagged", []))


def list_arguments(tool):
    """The arguments whose fixture values are whole lists, per tool under `$lists`.

    Barclay collects a repeated argument into one list, and the array assigns one value per
    argument, so a list the tool reads as a unit (the annotations a model is built over, the
    sensitivities a tranche file is cut at) can only be varied as a unit: each value is its
    elements separated by spaces, and each element is written as its own `--name element`.
    """
    path = REPO / "tools" / "coverage" / "fixtures.json"
    if not path.exists():
        return ()
    fixtures = json.loads(path.read_text())
    return tuple(fixtures.get("per_tool", {}).get(tool, {}).get("$lists", []))


def run_rows(options, array, held, workdir):
    """Every row of the array, against the oracle and optionally against the port."""
    rows, matched, rejected = [], 0, 0
    positional = positional_values(options.tool)
    tagged = tagged_arguments(options.tool)
    keep_output = output_on_failure(options.tool)
    lists = list_arguments(options.tool)
    outputs = set()
    if True:  # keeps the body's indentation while it lives in its own function
        if FIXTURES_DIR is None:
            build_fixtures(workdir)
        (workdir / "tmp").mkdir(exist_ok=True)
        for row in array["array"]:
            args = row_arguments(row, held)
            code, text, error = run_oracle(options.tool, args, workdir, positional, tagged, lists)
            reference = outcome(code, text, error, keep_output)
            if code != 0:
                rejected += 1
                if keep_output and text:
                    outputs.add(reference)
            else:
                outputs.add(reference)
            record = {"row": row["row"], "arguments": args, "reference": reference}
            if options.port:
                port_code, port_text, port_error = run_port(
                    options.port, options.tool, args, workdir, positional, tagged, lists
                )
                ours = outcome(port_code, port_text, port_error, keep_output)
                record["port"] = ours
                record["matched"] = ours == reference
                matched += 1 if ours == reference else 0
            rows.append(record)
            print(f"row {row['row']}: {'ok' if code == 0 else 'rejected'}"
                  + (f" port={'match' if record.get('matched') else 'differs'}"
                     if options.port else ""))

    if options.corpus:
        lines = [f"# {options.tool} covering array, t={options.t}"]
        for record in rows:
            lines.append(f"arguments\t{record['row']}\t{escape(' '.join(record['arguments']))}")
            lines.append(f"reference\t{record['row']}\t{escape(record['reference'])}")
            if "port" in record:
                lines.append(f"port\t{record['row']}\t{escape(record['port'])}")
        Path(options.corpus).write_text("\n".join(lines) + "\n")

    print(
        f"tool={options.tool} t={options.t} rows={len(rows)} rejected={rejected} "
        f"distinct_outputs={len(outputs)}"
        + (f" matched={matched} share={matched / len(rows):.3f}" if options.port else "")
    )
    return 0


